-- Reviewed checkpoint: explicit window and customer grain; no persisted writes.
SET REPORT_START = '2025-03-30';
SET REPORT_END_EXCLUSIVE = '2026-10-01';
SELECT CUSTOMER_ID, SUM(AMOUNT) AS NET_SPEND
FROM HOL_EXAMPLE_20261026.SOURCE.TRANSACTIONS
WHERE STATUS = 'COMPLETED'
  AND TRANSACTION_TIME >= TO_TIMESTAMP_NTZ($REPORT_START)
  AND TRANSACTION_TIME < TO_TIMESTAMP_NTZ($REPORT_END_EXCLUSIVE)
GROUP BY CUSTOMER_ID
ORDER BY NET_SPEND DESC, CUSTOMER_ID;
